'use strict';
/**
 * 中文别名生成（对应 start.hsp 25900-26010 的 random_title()）。
 *
 * 【源码】`*label_0316` 从 `data\ndata.csv`（15 列词素表，项目里是
 *   `web/assets/data/ndata.csv`）随机取一列 + 一行，按 `の / ・オブ・ / ザ・`
 *   等连接词拼两段，生成「気狂いの霧」「妖怪殺しの飛竜」这类异名；
 *   220553-220600 的「異名の選択」一次给 16 个候选 + 1 个「再抽選」。
 * 【本实现】原表是日文且无中文译文，这里按同样的「词素 A + 连接词 + 词素 B」
 *   结构内置中文词库，保证生成的别名是中文、可读、不重复。
 */
(function (global) {
  const Elona = global.Elona = global.Elona || {};

  /** 词素 A：修饰 / 主体 */
  const A = [
    '疯狂', '妖怪', '少女', '抵抗', '诅咒', '寂静', '孤高', '魔法', '宵暗', '绝对',
    '火焰', '流浪', '超越', '忘却', '奇迹', '白银', '漆黑', '苍蓝', '绯红', '深渊',
    '悠久', '无垢', '混沌', '圣洁', '暗黑', '灼热', '冰霜', '雷鸣', '疾风', '大地',
    '星屑', '月影', '太阳', '王者', '勇者', '贤者', '盗贼', '猎人', '诗人', '铁匠',
    '旅人', '亡者', '飞龙', '巨兽', '妖精', '巨人', '矮人', '机械', '傀儡', '幽灵',
    '幻影', '蔷薇', '荆棘', '水晶', '砂砾', '钢铁', '鲜血', '薄暮', '黎明', '残响',
    '剑', '盾', '弓', '杖', '花', '蝶', '狼', '猫', '鸦', '蛇', '狮', '鹰', '鬼', '神',
  ];
  /** 词素 B：客体 */
  const B = [
    '雾', '飞龙', '秩序', '至宝', '新娘', '地震', '孤高', '高塔', '梦幻', '无政府',
    '瞬间', '流浪者', '影子', '彼岸', '忘却', '将军', '之剑', '之盾', '王冠', '羽翼',
    '眼眸', '心脏', '灵魂', '歌谣', '诗篇', '誓约', '真名', '道路', '光辉', '黑暗',
    '炎', '冰', '雷', '风', '海', '天空', '大地', '星辰', '明月', '太阳', '梦境',
    '记忆', '轨迹', '残响', '眷属', '化身', '继承者', '终结者', '守护者', '破坏者',
    '调律者', '观测者', '编织者', '吟游者', '追猎者', '幸存者', '叛徒', '圣女', '魔女', '狂人',
  ];
  /** 连接词（对应源码 var_52 日文 / 英文分支） */
  const LINK = ['之', '之', '之', '的', '·', '·'];
  /** 前缀（对应「ザ・」「真」） */
  const PRE = ['', '', '', '', '', '·', '真·', '无双·'];
  /** 固定短语，增加变化（对应 ndata.csv 里现成的整词） */
  const FIXED = [
    '魔法之塔', '宵暗的梦幻', '绝对的无政府', '火焰时刻', '· 流浪者 ·',
    '影之萨夏', '遥远超越', '骨之忘却', '呼唤奇迹的将军', '抵抗之至宝',
    '被诅咒之妻', '寂静地震', '艾斯的孤高', '妖怪杀手的飞龙', '少女般的秩序',
    '疯狂之雾', '星屑的轨迹', '深渊的观测者', '白银的誓约', '无垢的圣女',
  ];

  function pick(rng, arr) { return arr[rng.rnd(arr.length)]; }

  /** 生成一条中文别名 */
  function one(rng) {
    const r = rng || Elona.rng;
    if (r.rnd(6) === 0) return pick(r, FIXED);
    const a = pick(r, A), b = pick(r, B);
    const link = pick(r, LINK);
    const pre = pick(r, PRE);
    // 「之剑 / 之盾」等 B 自带连接词时不再叠加
    if (/^[之的·・]/.test(b)) return pre + a + b;
    return pre + a + link + b;
  }

  /** 生成 n 条互不重复的中文别名 */
  function list(rng, n) {
    const r = rng || Elona.rng;
    const out = [], seen = Object.create(null);
    for (let i = 0; i < (n | 0 || 16) * 8 && out.length < (n | 0 || 16); i++) {
      const t = one(r);
      if (seen[t]) continue;
      seen[t] = 1;
      out.push(t);
    }
    return out;
  }

  Elona.TitleText = { one, list, A, B, LINK, PRE, FIXED };
})(window);
